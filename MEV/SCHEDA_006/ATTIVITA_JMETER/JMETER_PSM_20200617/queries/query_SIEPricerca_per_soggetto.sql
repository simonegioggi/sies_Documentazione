--USERID,PASSWORD,COGNOME,NOME,ANNODATANASCITA,MESEDATANASCITA,GIORNODATANASCITA,CODCOMUNENASCITA,CODSTATONASCITA
(SELECT 'userid,password,Cognome,Nome,AnnoDataNascita,MeseDataNascita,GiornoDataNascita,CodComuneNascita,CodStatoNascita' AS A  FROM DUAL ) 
UNION
SELECT '' || COD_OPERATORE_INSERIMENTO || ',' || 'ciccio'  || ',' || COGNOME ||',,,,,,'||COD_STATO_NASCITA   
  FROM (  
  SELECT  S.COD_OPERATORE_INSERIMENTO,  S.COGNOME,S.COD_STATO_NASCITA,
   RANK() OVER(PARTITION BY S.COD_OPERATORE_INSERIMENTO ORDER BY S.ID_SOGGETTO) AS RNK
    FROM   SOGGETTO S,
           UFFICIO U,
           FASCICOLO_SIEP F
    WHERE S.COD_STATO_NASCITA='039'
    AND S.COD_UFFICIO_INSERIMENTO = U.COD_UFFICIO
    AND U.COD_DISTRETTO = '00127200602' -- TORINO
          ---- NON DEVE ESTRARRE I MIGRATI
    AND S.COD_OPERATORE_INSERIMENTO NOT LIKE 'res%'
       -- NON DEVE ESTRARRE I PROVENIENTI DA NSC
    AND S.COD_OPERATORE_INSERIMENTO NOT LIKE 'nsc%'
    AND S.COD_OPERATORE_INSERIMENTO IN
                (SELECT U.COD_UTENTE
                   FROM UTENTE_UFFICIO UF,
                        UTENTE U,
                        (SELECT *
                           FROM UTENTE_PROFILO PR
                          WHERE PR.PRF_COD_PROFILO <> '90'
                            AND PR.PRF_COD_PROFILO <> '99') P
                  WHERE U.DATA_FINE_VALIDITA IS NULL
                    AND P.UTE_COD_UTENTE = U.COD_UTENTE
                    AND UF.UTE_COD_UTENTE = U.COD_UTENTE)     
     -- JOIN CON IL FASCICOLO
     AND F.COD_UFFICIO_INSERIMENTO = U.COD_UFFICIO                     
     AND F.SOG_ID_SOGGETTO=S.ID_SOGGETTO
    ORDER BY DBMS_RANDOM.VALUE  )
     WHERE RNK = 1
ORDER BY A DESC
