SELECT /*'test',
       'test',*/
       distinct AVV.COD_FISCALE,
       UFF.COD_DISTRETTO,
       uff.cod_ufficio,
       UFF.COD_TIPO_UFFICIO,
       FASC.CHIAVE_ANNO     CHIAVE_ANNO,
       FASC.CHIAVE_PROGR    CHIAVE_PROGR
  FROM SOGGETTO SOGG, GENERALE_PROCEDIMENTO GP
  LEFT OUTER JOIN UDIENZA_PROCEDIMENTO UP
    ON (UP.GEN_PRID_GENERALE_PROCEDIMENTO = GP.ID_GENERALE_PROCEDIMENTO)
  LEFT OUTER JOIN UDIENZA UD
    ON (UD.ID_UDIENZA = GP.UDI_ID_UDIENZA), TENORE TEN, CG_REF_CODES
 DESCR_OGGETTO_PROCEDIMENTO, CG_REF_CODES POS_GIURIDICA, CG_REF_CODES
 NAZIONE, UFFICIO UFF, CG_REF_CODES STATO_FASCICOLO, COMUNE
 DESCR_COM_UFF, COMUNE DESCR_COM_NASCITA, CG_REF_CODES TIPO_ATTO,
 CG_REF_CODES MITTENTE_ATTO, CG_REF_CODES TIPO_REGISTRO, COMUNE
 DESCR_COM_MIT, MAGISTRATO_RELATORE MAG, MAGISTRATO M, AVVOCATO AVV,
 AVVOCATO_FASCICOLO_SIUS AVV_FAS, FASCICOLO_SIUS FASC
  LEFT OUTER JOIN V_SOGSIUS_ETA VSE
    ON (FASC.ID_FASCICOLO_SIUS = VSE.ID_FASCICOLO_SIUS)
  LEFT OUTER JOIN LUOGO_DETENZIONE LD
    ON (FASC.ID_FASCICOLO_SIUS = LD.FAS_SIU_ID_FASCICOLO_SIUS)
  LEFT OUTER JOIN ISTITUTO_DETENZIONE ID
    ON (LD.IST_DET_ID_ISTITUTO_DETENZIONE = ID.ID_ISTITUTO_DETENZIONE)
  LEFT OUTER JOIN CG_REF_CODES ISD
    ON (ISD.RV_LOW_VALUE = ID.COD_TIPO_ISTITUTO AND
       ISD.RV_DOMAIN = 'TIPO_ISTITUTO')
 WHERE FASC.SOG_ID_SOGGETTO = SOGG.ID_SOGGETTO
   AND FASC.ID_FASCICOLO_SIUS = GP.FAS_SIU_ID_FASCICOLO_SIUS
   AND DESCR_OGGETTO_PROCEDIMENTO.RV_DOMAIN = 'OGGETTO_PROCEDIMENTO'
   AND GP.COD_OGGETTO_PROCEDIMENTO =
       DESCR_OGGETTO_PROCEDIMENTO.RV_LOW_VALUE
   AND POS_GIURIDICA.RV_DOMAIN = 'POSIZIONE_GIURIDICA'
   AND (NVL(GP.COD_POSIZIONE_GIURIDICA, '-') = POS_GIURIDICA.RV_LOW_VALUE)
   AND UFF.COD_UFFICIO = FASC.CHIAVE_UFFICIO
   AND UFF.COD_COMUNE = DESCR_COM_UFF.COD_COMUNE
   AND SOGG.COD_COMUNE_NASCITA = DESCR_COM_NASCITA.COD_COMUNE
   AND FASC.ID_FASCICOLO_SIUS = VSE.ID_FASCICOLO_SIUS
   AND UFF.COD_UFFICIO IN
       (SELECT U.COD_UFFICIO
          FROM UFFICIO U, COMUNE C
         WHERE U.COD_TIPO_UFFICIO = 'TDS'
           AND U.COD_COMUNE = C.COD_COMUNE
           AND U.COD_DISTRETTO = '00127200602')
   AND ((NVL(VSE.ETA_ORA, 18) >= 18) OR
       (FASC.COD_UFFICIO_INSERIMENTO IN
       (SELECT U.COD_UFFICIO
            FROM UFFICIO U, COMUNE C
           WHERE U.COD_TIPO_UFFICIO = 'AAA'
             AND U.COD_COMUNE = C.COD_COMUNE
             AND U.COD_DISTRETTO = '00127200602')))
   AND NAZIONE.RV_DOMAIN = 'NAZIONE'
   AND NAZIONE.RV_LOW_VALUE = SOGG.COD_STATO_NASCITA
   AND NVL(LD.DATA_INSERIMENTO, TO_DATE('01/01/1900', 'dd/mm/yyyy')) =
       NVL((SELECT MAX(DATA_INSERIMENTO)
             FROM LUOGO_DETENZIONE
            WHERE FAS_SIU_ID_FASCICOLO_SIUS = FASC.ID_FASCICOLO_SIUS),
           TO_DATE('01/01/1900', 'dd/mm/yyyy'))
   AND (TIPO_ATTO.RV_DOMAIN = 'TIPO_ATTO' AND
       NVL(GP.COD_TIPO_ATTO, '-') = TIPO_ATTO.RV_LOW_VALUE)
   AND (MITTENTE_ATTO.RV_DOMAIN = 'MITTENTE_ATTO' AND
       NVL(GP.COD_TIPO_MITTENTE_ATTO, '-') = MITTENTE_ATTO.RV_LOW_VALUE)
   AND (GP.COD_SEDE_MITTENTE = DESCR_COM_MIT.COD_COMUNE)
   AND (TEN.GEN_PRID_GENERALE_PROCEDIMENTO = GP.ID_GENERALE_PROCEDIMENTO)
   AND MAG.FAS_SIU_ID_FASCICOLO_SIUS = FASC.ID_FASCICOLO_SIUS
   AND MAG.DATA_FINE IS NULL
   AND M.COD_MAGISTRATO = MAG.MAG_COD_MAGISTRATO
   AND M.DATA_FINE_VALIDITA IS NULL
   AND AVV.ID_AVVOCATO = AVV_FAS.AVV_ID_AVVOCATO
   AND FASC.ID_FASCICOLO_SIUS = AVV_FAS.FAS_SIU_ID_FASCICOLO_SIUS
   AND AVV_FAS.DATA_FINE_VALIDITA IS NULL
   AND (STATO_FASCICOLO.RV_DOMAIN = 'STATO_FASCICOLO' AND
       NVL(STATO_FASCICOLO.RV_LOW_VALUE, '-') = FASC.COD_STATO_FASCICOLO)
   AND (TIPO_REGISTRO.RV_DOMAIN = 'TIPO_REGISTRO' AND
       NVL(GP.COD_TIPO_REGISTRO, '-') = TIPO_REGISTRO.RV_LOW_VALUE)
   AND AVV.COD_FISCALE IS NOT NULL
   order by 4 desc,5 desc
